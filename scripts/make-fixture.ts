/**
 * Generates a synthetic FIT file for tests: a 120-second run with two laps.
 * Contains no GPS and no real data, so it is safe to commit.
 * Usage: npx tsx scripts/make-fixture.ts
 */
import { writeFileSync } from "node:fs";
import { Encoder, Profile } from "@garmin/fitsdk";

const start = new Date("2026-01-15T07:00:00.000Z");
const at = (s: number) => new Date(start.getTime() + s * 1000);
const encoder = new Encoder();
const { MesgNum } = Profile;
// The SDK's Encodable type needs literal message numbers; the profile table gives plain numbers.
const write = (mesg: Record<string, unknown>) => encoder.writeMesg(mesg as never);

write({ mesgNum: MesgNum.FILE_ID, type: "activity", manufacturer: "development", product: 1, timeCreated: start, serialNumber: 1 });
for (let t = 0; t < 120; t++) {
	write({
		mesgNum: MesgNum.RECORD,
		timestamp: at(t),
		distance: t * 3,
		enhancedSpeed: 3,
		enhancedAltitude: 100 + t / 10,
		heartRate: 140 + (t % 10),
		cadence: 85,
		fractionalCadence: 0.5,
		power: 250,
	});
}
const lap = (from: number, to: number, index: number) =>
	write({
		mesgNum: MesgNum.LAP,
		messageIndex: index,
		timestamp: at(to),
		startTime: at(from),
		totalTimerTime: to - from,
		totalElapsedTime: to - from,
		totalDistance: (to - from) * 3,
		enhancedAvgSpeed: 3,
		avgHeartRate: 145,
		maxHeartRate: 149,
		avgCadence: 85,
		avgFractionalCadence: 0.5,
		avgPower: 250,
		totalAscent: 6,
		totalDescent: 0,
		sport: "running",
		intensity: "active",
		lapTrigger: "distance",
	});
lap(0, 60, 0);
lap(60, 120, 1);
write({ mesgNum: MesgNum.SESSION, timestamp: at(120), startTime: start, sport: "running", subSport: "generic", totalTimerTime: 120, totalElapsedTime: 120, totalDistance: 360 });
write({ mesgNum: MesgNum.ACTIVITY, timestamp: at(120), numSessions: 1, totalTimerTime: 120, type: "manual", event: "activity", eventType: "stop" });

const bytes = encoder.close();
const base64 = Buffer.from(bytes).toString("base64");
writeFileSync(new URL("../test/fixtures/synthetic-run.ts", import.meta.url), `// Generated by scripts/make-fixture.ts. Synthetic: no GPS, no real data.\nexport const SYNTHETIC_RUN_FIT = Uint8Array.from(atob(\n\t"${base64}",\n), (c) => c.charCodeAt(0));\n`);
console.log("wrote fixture,", bytes.length, "bytes");
